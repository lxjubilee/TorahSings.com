#!/usr/bin/env node
/**
 * build-hebraic-articles — bake the Hebraic Christianity corpus into the repo.
 *
 * Reads the markdown articles off the drive (production has no J:), parses the
 * frontmatter + markdown body, and emits a committed TS array that the
 * /hebraic-christianity pages render. Mirrors scripts/build-angels-catalog.mjs.
 *
 *   node scripts/build-hebraic-articles.mjs
 *   env: ARTICLES_ROOT (default J:\torahsings.com\articles\hebraic)
 */
import { readdirSync, readFileSync, writeFileSync } from 'node:fs';
import { join } from 'node:path';

const ROOT = process.env.ARTICLES_ROOT || 'J:/torahsings.com/articles/hebraic';
const OUT = new URL('../src/content/hebraic-articles.ts', import.meta.url);

const HEBREW = ['א','ב','ג','ד','ה','ו','ז','ח','ט','י','כ','ל','מ','נ','ס','ע','פ','צ','ק','ר','ש','ת'];

/** djb2 → unsigned int, for deterministic hue/glyph from a slug. */
function hash(s) {
  let h = 5381;
  for (let i = 0; i < s.length; i++) h = ((h << 5) + h + s.charCodeAt(i)) >>> 0;
  return h;
}

function unquote(v) {
  v = v.trim();
  if (v.length >= 2 && ((v[0] === '"' && v.at(-1) === '"') || (v[0] === "'" && v.at(-1) === "'"))) {
    v = v.slice(1, -1);
  }
  return v.replace(/\\"/g, '"');
}

/** Parse the leading `---` frontmatter block into {key: value}. */
function parseFrontmatter(text) {
  if (!text.startsWith('---')) return { fm: {}, body: text };
  const end = text.indexOf('\n---', 3);
  if (end < 0) return { fm: {}, body: text };
  const fmText = text.slice(3, end);
  const body = text.slice(text.indexOf('\n', end + 1) + 1);
  const fm = {};
  for (const line of fmText.split('\n')) {
    const m = line.match(/^([A-Za-z_][A-Za-z0-9_]*):\s?(.*)$/);
    if (m) fm[m[1]] = unquote(m[2]);
  }
  return { fm, body };
}

/** Markdown body -> HebraicBlock[]. Inline bold/italic markers are kept in text. */
function parseBody(body) {
  const lines = body.split('\n');
  const blocks = [];
  let para = [];
  let quote = [];
  const flushPara = () => { if (para.length) { blocks.push({ type: 'p', text: para.join(' ').trim() }); para = []; } };
  const flushQuote = () => {
    if (!quote.length) return;
    let text = quote.join(' ').trim();
    let cite;
    const c = text.match(/\(([^()]+)\)\s*$/);
    if (c && /\d/.test(c[1])) { cite = c[1].trim(); text = text.slice(0, c.index).trim(); }
    blocks.push({ type: 'quote', text, ...(cite ? { cite } : {}) });
    quote = [];
  };
  for (const raw of lines) {
    const t = raw.trim();
    if (t === '') { flushPara(); flushQuote(); continue; }
    if (t.startsWith('>')) { flushPara(); quote.push(t.replace(/^>\s?/, '')); continue; }
    flushQuote();
    if (/^#{2,4}\s+/.test(t)) { flushPara(); blocks.push({ type: 'h', text: t.replace(/^#{2,4}\s+/, '') }); continue; }
    if (/^(-{3,}|\*{3,}|_{3,})$/.test(t)) { flushPara(); blocks.push({ type: 'hr' }); continue; }
    para.push(t);
  }
  flushPara();
  flushQuote();
  // Trim a leading/trailing hr (the trailing "--- disclaimer" rule reads cleaner without a bare line).
  while (blocks.length && blocks[0].type === 'hr') blocks.shift();
  while (blocks.length && blocks.at(-1).type === 'hr') blocks.pop();
  return blocks;
}

function wordCount(blocks) {
  return blocks.reduce((n, b) => n + (b.text ? b.text.replace(/[*_>#]/g, ' ').split(/\s+/).filter(Boolean).length : 0), 0);
}

const files = readdirSync(ROOT).filter((f) => f.toLowerCase().endsWith('.md')).sort();
const articles = [];
const problems = [];
for (const file of files) {
  try {
    const { fm, body } = parseFrontmatter(readFileSync(join(ROOT, file), 'utf8'));
    const slug = fm.slug || file.replace(/\.md$/i, '');
    if (!fm.title) { problems.push(`${file}: no title`); continue; }
    const blocks = parseBody(body);
    const h = hash(slug);
    articles.push({
      order: Number.parseInt(fm.order, 10) || 0,
      slug,
      title: fm.title,
      dek: fm.excerpt || '',
      presenter: fm.author || 'Zev Inspire',
      office: fm.office || '',
      readingTime: Math.max(1, Math.round(wordCount(blocks) / 200)),
      hue: h % 360,
      glyph: HEBREW[h % HEBREW.length],
      blocks,
    });
  } catch (e) {
    problems.push(`${file}: ${e.message}`);
  }
}
articles.sort((a, b) => a.order - b.order);

const withImagesNote = `${articles.length} articles`;
const header = `// AUTO-GENERATED by scripts/build-hebraic-articles.mjs — do not edit by hand.
// Source: ${ROOT}
// ${withImagesNote}.
import type { HebraicArticle } from '@/lib/hebraic';

export const hebraicArticles: HebraicArticle[] = `;
writeFileSync(OUT, header + JSON.stringify(articles, null, 2) + ';\n', 'utf8');

console.log(`Wrote ${articles.length} articles -> src/content/hebraic-articles.ts`);
const noBlocks = articles.filter((a) => a.blocks.length === 0).length;
if (noBlocks) console.log(`  ⚠ ${noBlocks} article(s) parsed with 0 blocks`);
if (problems.length) { console.log('PROBLEMS:'); for (const p of problems) console.log('  ' + p); }
