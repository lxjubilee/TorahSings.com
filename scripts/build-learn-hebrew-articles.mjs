#!/usr/bin/env node
/**
 * build-learn-hebrew-articles — bake the Learn Hebrew word-articles into the repo.
 *
 * Like build-hebraic-articles, but the markdown body carries inline images:
 *   ![alt text](<slug>-N.webp "the generation prompt")
 * which become `image` blocks (src = filename, alt = alt text). The prompt in the
 * title stays in the .md for tools/ArticleImageStudio to read; it is not needed
 * in the site data. The first inline image becomes the card thumbnail.
 *
 *   node scripts/build-learn-hebrew-articles.mjs
 *   env: LEARN_HEBREW_ROOT (default J:\torahsings.com\articles\learn-hebrew)
 */
import { readdirSync, readFileSync, writeFileSync } from 'node:fs';
import { join } from 'node:path';

const ROOT = process.env.LEARN_HEBREW_ROOT || 'J:/torahsings.com/articles/learn-hebrew';
const OUT = new URL('../src/content/learn-hebrew-articles.ts', import.meta.url);

const HEBREW = ['א','ב','ג','ד','ה','ו','ז','ח','ט','י','כ','ל','מ','נ','ס','ע','פ','צ','ק','ר','ש','ת'];
const IMG_RX = /^!\[(?<alt>[^\]]*)\]\((?<src>[^\s)]+)(?:\s+"[^"]*")?\)\s*$/;

function hash(s) { let h = 5381; for (let i = 0; i < s.length; i++) h = ((h << 5) + h + s.charCodeAt(i)) >>> 0; return h; }

function unquote(v) {
  v = v.trim();
  if (v.length >= 2 && ((v[0] === '"' && v.at(-1) === '"') || (v[0] === "'" && v.at(-1) === "'"))) v = v.slice(1, -1);
  return v.replace(/\\"/g, '"');
}

function parseFrontmatter(text) {
  if (!text.startsWith('---')) return { fm: {}, body: text };
  const end = text.indexOf('\n---', 3);
  if (end < 0) return { fm: {}, body: text };
  const fm = {};
  for (const line of text.slice(3, end).split('\n')) {
    const m = line.match(/^([A-Za-z_][A-Za-z0-9_]*):\s?(.*)$/);
    if (m) fm[m[1]] = unquote(m[2]);
  }
  return { fm, body: text.slice(text.indexOf('\n', end + 1) + 1) };
}

function parseBody(body) {
  const lines = body.split('\n');
  const blocks = [];
  let para = [];
  let quote = [];
  const flushPara = () => { if (para.length) { blocks.push({ type: 'p', text: para.join(' ').trim() }); para = []; } };
  const flushQuote = () => {
    if (!quote.length) return;
    let text = quote.join(' ').trim();
    let cite;
    const c = text.match(/\(([^()]+)\)\s*$/);
    if (c && /\d/.test(c[1])) { cite = c[1].trim(); text = text.slice(0, c.index).trim(); }
    blocks.push({ type: 'quote', text, ...(cite ? { cite } : {}) });
    quote = [];
  };
  for (const raw of lines) {
    const t = raw.trim();
    if (t === '') { flushPara(); flushQuote(); continue; }
    const img = t.match(IMG_RX);
    if (img) { flushPara(); flushQuote(); blocks.push({ type: 'image', src: img.groups.src, alt: img.groups.alt }); continue; }
    if (t.startsWith('>')) { flushPara(); quote.push(t.replace(/^>\s?/, '')); continue; }
    flushQuote();
    if (/^#{2,4}\s+/.test(t)) { flushPara(); blocks.push({ type: 'h', text: t.replace(/^#{2,4}\s+/, '') }); continue; }
    if (/^(-{3,}|\*{3,}|_{3,})$/.test(t)) { flushPara(); blocks.push({ type: 'hr' }); continue; }
    para.push(t);
  }
  flushPara();
  flushQuote();
  while (blocks.length && blocks[0].type === 'hr') blocks.shift();
  while (blocks.length && blocks.at(-1).type === 'hr') blocks.pop();
  return blocks;
}

function wordCount(blocks) {
  return blocks.reduce((n, b) => n + (b.text ? b.text.replace(/[*_>#]/g, ' ').split(/\s+/).filter(Boolean).length : 0), 0);
}

const files = readdirSync(ROOT).filter((f) => f.toLowerCase().endsWith('.md')).sort();
const articles = [];
for (const file of files) {
  const { fm, body } = parseFrontmatter(readFileSync(join(ROOT, file), 'utf8'));
  const slug = fm.slug || file.replace(/\.md$/i, '');
  if (!fm.title) { console.log(`SKIP ${file}: no title`); continue; }
  const blocks = parseBody(body);
  const firstImage = blocks.find((b) => b.type === 'image');
  const h = hash(slug);
  articles.push({
    order: Number.parseInt(fm.order, 10) || 0,
    slug,
    title: fm.title,
    dek: fm.excerpt || '',
    presenter: fm.author || 'Zev Inspire',
    office: fm.office || '',
    readingTime: Math.max(1, Math.round(wordCount(blocks) / 200)),
    hue: h % 360,
    glyph: HEBREW[h % HEBREW.length],
    thumb: firstImage ? firstImage.src : null,
    blocks,
  });
}
articles.sort((a, b) => a.order - b.order);

const header = `// AUTO-GENERATED by scripts/build-learn-hebrew-articles.mjs — do not edit by hand.
// Source: ${ROOT}
// ${articles.length} articles.
import type { LearnHebrewArticle } from '@/lib/learn-hebrew';

export const learnHebrewArticles: LearnHebrewArticle[] = `;
writeFileSync(OUT, header + JSON.stringify(articles, null, 2) + ';\n', 'utf8');

const imgCount = articles.reduce((n, a) => n + a.blocks.filter((b) => b.type === 'image').length, 0);
console.log(`Wrote ${articles.length} articles (${imgCount} inline images) -> src/content/learn-hebrew-articles.ts`);
