#!/usr/bin/env node
/**
 * wire-article-images — the OUTPUT half of the Article Image Studio bridge.
 *
 * tools/ArticleImageStudio renders hero images into
 *   <ARTICLES_ROOT>\hebraic\images\<slug>.webp
 * This script scans that folder and regenerates the manifest the site reads,
 *   src/content/article-images.ts   (slug -> filename)
 * so an article whose slug has an image starts using it (ArticleArt prefers the
 * CDN image over the CelestialArt placeholder). Run it after generating images,
 * and after deploying them to the CDN.
 *
 * Usage:  node scripts/wire-article-images.mjs
 * Env:    ARTICLES_ROOT  (default J:\torahsings.com\articles)
 */

import { existsSync, readdirSync, writeFileSync } from 'node:fs';
import { dirname, extname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

const __dirname = dirname(fileURLToPath(import.meta.url));
const ROOT = join(__dirname, '..');

const ARTICLES_ROOT = process.env.ARTICLES_ROOT || 'J:\\torahsings.com\\articles';
const imagesDir = join(ARTICLES_ROOT, 'hebraic', 'images');
const manifestPath = join(ROOT, 'src', 'content', 'article-images.ts');

const IMAGE_EXTS = new Set(['.webp', '.png', '.jpg', '.jpeg']);

function scan() {
  if (!existsSync(imagesDir)) return {};
  const map = {};
  for (const name of readdirSync(imagesDir).sort()) {
    const ext = extname(name).toLowerCase();
    if (!IMAGE_EXTS.has(ext)) continue;
    const slug = name.slice(0, -ext.length);
    // Prefer .webp if both a .webp and another format exist for one slug.
    if (map[slug] && extname(map[slug]).toLowerCase() === '.webp') continue;
    map[slug] = name;
  }
  return map;
}

function render(map) {
  const entries = Object.keys(map)
    .sort()
    .map((slug) => `  ${JSON.stringify(slug)}: ${JSON.stringify(map[slug])},`)
    .join('\n');
  return (
    '// GENERATED by scripts/wire-article-images.mjs — do not edit by hand.\n' +
    '//\n' +
    '// Maps an article `slug` to the filename of its generated hero image in the\n' +
    '// hebraic image set (rendered by tools/ArticleImageStudio into\n' +
    '// J:\\torahsings.com\\articles\\hebraic\\images and deployed to\n' +
    '// https://cdn.torahsings.com/articles/hebraic/images). An empty map means no\n' +
    '// images have been generated yet, in which case every article falls back to the\n' +
    '// procedural CelestialArt placeholder.\n' +
    'export const articleImages: Record<string, string> = ' +
    (entries ? `{\n${entries}\n};\n` : '{};\n')
  );
}

const map = scan();
writeFileSync(manifestPath, render(map), 'utf8');
const n = Object.keys(map).length;
console.log(`Wrote ${manifestPath.replace(ROOT + '\\', '')} — ${n} article image(s) from ${imagesDir}`);
if (n === 0) console.log('  (no images yet — generate some with tools/ArticleImageStudio first)');
