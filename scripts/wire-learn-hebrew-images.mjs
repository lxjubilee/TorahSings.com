#!/usr/bin/env node
/**
 * wire-learn-hebrew-images — refresh the manifest of which Learn Hebrew inline
 * infographics exist, from J:\torahsings.com\articles\learn-hebrew\images.
 * Run after generating images with tools/ArticleImageStudio (and after
 * deploying them to R2). Anything not listed renders an "image coming" panel.
 *
 *   node scripts/wire-learn-hebrew-images.mjs
 *   env: LEARN_HEBREW_ROOT (default J:\torahsings.com\articles\learn-hebrew)
 */
import { existsSync, readdirSync, writeFileSync } from 'node:fs';
import { dirname, extname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

const ROOT = process.env.LEARN_HEBREW_ROOT || 'J:/torahsings.com/articles/learn-hebrew';
const imagesDir = join(ROOT, 'images');
const OUT = join(dirname(fileURLToPath(import.meta.url)), '..', 'src', 'content', 'learn-hebrew-images.ts');

const files = existsSync(imagesDir)
  ? readdirSync(imagesDir).filter((f) => extname(f).toLowerCase() === '.webp').sort()
  : [];

const entries = files.map((f) => `  ${JSON.stringify(f)}: ${JSON.stringify(f)},`).join('\n');
const body =
  '// GENERATED by scripts/wire-learn-hebrew-images.mjs — do not edit by hand.\n' +
  '//\n' +
  '// Maps a generated inline-image filename to itself for every Learn Hebrew\n' +
  '// infographic present on disk. A filename not listed has not been generated yet\n' +
  '// and renders an "image coming" panel.\n' +
  'export const learnHebrewImages: Record<string, string> = ' +
  (entries ? `{\n${entries}\n};\n` : '{};\n');

writeFileSync(OUT, body, 'utf8');
console.log(`Wrote src/content/learn-hebrew-images.ts — ${files.length} image(s) from ${imagesDir}`);
